"""DVC stage `summary`: one results file with every table the final report needs."""

from __future__ import annotations

from phishshield.config import REPORTS_DIR, ensure_dirs
from phishshield.utils.common import get_logger, load_json

log = get_logger("summary")


def _read(name: str) -> str:
    p = REPORTS_DIR / name
    return p.read_text().strip() if p.exists() else "_not generated_"


def main() -> None:
    ensure_dirs()
    s = load_json(REPORTS_DIR / "student_metrics.json")
    st, tt = s["student_test"], s["teacher_test"]
    shap = load_json(REPORTS_DIR / "shap_importance.json") if (REPORTS_DIR / "shap_importance.json").exists() else {}
    promo = load_json(REPORTS_DIR / "promotion.json") if (REPORTS_DIR / "promotion.json").exists() else {}

    distil = "\n".join([
        "| Model | Params | F1 | Recall | FNR | Latency (ms, 1 URL) |", "|---|---|---|---|---|---|",
        f"| Hybrid DistilBERT (teacher) | {s['teacher_params']:,} | {tt['f1']:.4f} | {tt['recall']:.4f} | {tt['fnr']:.4f} | "
        f"{s['latency_ms']['teacher_torch']:.1f} |",
        f"| CharCNN student (ONNX) | {s['student_params']:,} | {st['f1']:.4f} | {st['recall']:.4f} | {st['fnr']:.4f} | "
        f"{s['latency_ms']['student_onnx_cpu']:.2f} |",
        "", f"Compression **{s['compression_ratio']:.0f}x**, speed-up **{s['speedup']:.0f}x**, "
        f"teacher-student agreement **{s['teacher_student_agreement']:.2%}**, ONNX size {s['onnx_size_mb']:.2f} MB, "
        f"ONNX vs PyTorch max error {s['onnx_max_abs_error']:.1e}."])

    md = f"""# PhishShield AI - final results

Generated by `dvc repro`. Stream/drift results (E4, E5) are a **controlled simulation** (see build_stream).

## E1. Baselines vs main model (test set)
{_read("model_comparison.md")}

## E2. Ablation - contribution of each branch
{_read("ablation.md")}

## E3. Knowledge distillation (serving model)
{distil}

Serving champion: **{promo.get("version", "?")}** (promoted: {promo.get("promoted", "?")}).

## E4. Drift detection over the stream
{_read("drift_detection.md")}

## E5. Update strategies (prequential, drift stream)
{_read("strategy_comparison.md")}

## E6. Top engineered features (mean |SHAP|)
""" + "\n".join(f"{i + 1}. `{k}` - {v:.4f}" for i, (k, v) in enumerate(list(shap.items())[:10])) + "\n"
    (REPORTS_DIR / "final_results.md").write_text(md)
    log.info("Wrote reports/final_results.md")


if __name__ == "__main__":
    main()
